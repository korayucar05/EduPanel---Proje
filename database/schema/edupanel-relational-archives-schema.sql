CREATE TABLE IF NOT EXISTS kayip_diploma_kayitlari (
  okul_id VARCHAR(20) NOT NULL,
  kayit_id VARCHAR(191) NOT NULL,
  tc_kimlik_no VARCHAR(20) NULL,
  ad_soyad VARCHAR(200) NULL,
  baba_adi VARCHAR(150) NULL,
  anne_adi VARCHAR(150) NULL,
  dogum_yeri VARCHAR(150) NULL,
  dogum_tarihi VARCHAR(40) NULL,
  ogretim_yili VARCHAR(40) NULL,
  alani VARCHAR(150) NULL,
  sinifi VARCHAR(80) NULL,
  okul_numarasi VARCHAR(80) NULL,
  diploma_tarihi VARCHAR(40) NULL,
  diploma_no VARCHAR(80) NULL,
  diploma_notu VARCHAR(40) NULL,
  yabanci_dili VARCHAR(100) NULL,
  bos_alan TEXT NULL,
  basvuran_kendisi TINYINT(1) NULL,
  basvuran_ad_soyad VARCHAR(200) NULL,
  basvuran_yakinlik VARCHAR(100) NULL,
  belge_nedeni TEXT NULL,
  belge_sayisi VARCHAR(80) NULL,
  islem_yapan_kullanici VARCHAR(200) NULL,
  guncellenme_zamani VARCHAR(40) NOT NULL,
  PRIMARY KEY (okul_id, kayit_id),
  KEY idx_kayip_diploma_tc (okul_id, tc_kimlik_no),
  KEY idx_kayip_diploma_okul_no (okul_id, okul_numarasi),
  KEY idx_kayip_diploma_ad (okul_id, ad_soyad),
  CONSTRAINT fk_kayip_diploma_okul FOREIGN KEY (okul_id)
    REFERENCES okullar (okul_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

